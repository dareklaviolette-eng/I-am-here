// Regenerates globe/wildlife-samples.json from the SAMPLE (synthetic) tracks built into wildlife/index.html.
// node globe/tools/gen-wildlife.mjs   (run from the repo root). Keeps ~150 points per track for the map.
import fs from 'node:fs';
const html = fs.readFileSync('wildlife/index.html', 'utf8');
const core = /\/\* CORE-BEGIN[\s\S]*?\*\/([\s\S]*?)\/\* CORE-END \*\//.exec(html)[1];
const api = new Function(core + '\nreturn { genEagleCSV, genSharkCSV };')();
const lastPing = (csv) => { const l = csv.trim().split('\n'), r = l[l.length - 1].split(','); return new Date(r[2].replace(' ', 'T') + 'Z').toISOString(); };
const animalId = (csv) => csv.trim().split('\n')[1].split(',')[9];
function pts(csv) {
  const rows = csv.trim().split('\n').slice(1).map((l) => l.split(','));
  const all = rows.map((r) => [+(+r[4]).toFixed(5), +(+r[3]).toFixed(5), +r[2] ? +r[2] : Date.parse(r[2])]);
  const step = Math.max(1, Math.ceil(all.length / 150)), out = all.filter((_, i) => i % step === 0);
  if (out[out.length - 1] !== all[all.length - 1]) out.push(all[all.length - 1]);
  return out.map((p) => [p[0], p[1]]);
}
const eagle = api.genEagleCSV(), shark = api.genSharkCSV();
const out = {
  note: 'SAMPLE (synthetic) tracks generated by wildlife/index.html; NOT real animal data.',
  tracks: [
    // tracker: who runs the tag (real tracks: e.g. Movebank, OCEARCH); species + wiki: for the card's species photo (Wikimedia Commons)
    { id: 'eagle', name: 'Bald eagle', label: 'Bald eagle, lake & river soar', tag: '4417', tracker: 'Sample track', species: 'Bald eagle',
      sci: 'Haliaeetus leucocephalus', wiki: 'Bald eagle', animal: animalId(eagle), lastPing: lastPing(eagle), path: pts(eagle) },
    { id: 'shark', name: 'White shark', label: 'White shark, coastal migration', tag: '2208', tracker: 'Sample track', species: 'White shark',
      sci: 'Carcharodon carcharias', wiki: 'Great white shark', animal: animalId(shark), lastPing: lastPing(shark), path: pts(shark) },
  ],
};
fs.writeFileSync('globe/wildlife-samples.json', JSON.stringify(out));
console.log(out.tracks.map((t) => `${t.id}: ${t.path.length} pts, last ${t.path[t.path.length - 1]}`).join('\n'));
